function buildKeyframes(from, steps) {
    const keys = new Set([...Object.keys(from), ...steps.flatMap(s => Object.keys(s))]);
    const keyframes = {};
    keys.forEach(k => { keyframes[k] = [from[k], ...steps.map(s => s[k])]; });
    return keyframes;
}

