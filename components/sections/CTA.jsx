/* ─── Animated counter ───────────────────────────────────── */
function Counter({ end, suffix = "" }) {
    const [val, setVal] = useState(0);
    const ref = useRef(null);
    useEffect(() => {
        const obs = new IntersectionObserver(([e]) => {
            if (e.isIntersecting) {
                let i = 0;
                const step = Math.ceil(end / 50);
                const t = setInterval(() => {
                    i += step;
                    if (i >= end) { setVal(end); clearInterval(t); } else setVal(i);
                }, 35);
            }
        }, { threshold: 0.5 });
        if (ref.current) obs.observe(ref.current);
        return () => obs.disconnect();
    }, [end]);
    return <span ref={ref}>{val}{suffix}</span>;
}

/* ─── Typewriter ─────────────────────────────────────────── */
function TypewriterLines({ lines, speed = 45 }) {
    const [out, setOut] = useState([]);
    const [lineIdx, setLineIdx] = useState(0);
    const [charIdx, setCharIdx] = useState(0);

    useEffect(() => {
        if (lineIdx >= lines.length) return;
        const line = lines[lineIdx];
        if (charIdx < line.length) {
            const t = setTimeout(() => {
                setOut(prev => {
                    const copy = [...prev];
                    copy[lineIdx] = (copy[lineIdx] || "") + line[charIdx];
                    return copy;
                });
                setCharIdx(c => c + 1);
            }, speed);
            return () => clearTimeout(t);
        } else {
            const t = setTimeout(() => { setLineIdx(l => l + 1); setCharIdx(0); }, 300);
            return () => clearTimeout(t);
        }
    }, [lineIdx, charIdx, lines, speed]);

    return (
        <div className="font-mono text-[11px] space-y-1">
            {lines.map((line, i) => (
                <div key={i} className={i < lineIdx ? "opacity-100" : i === lineIdx ? "opacity-100" : "opacity-0"}>
                    {i <= lineIdx ? (out[i] || "") : ""}
                    {i === lineIdx && <span className="animate-pulse text-[#39d353]">█</span>}
                </div>
            ))}
        </div>
    );
}

